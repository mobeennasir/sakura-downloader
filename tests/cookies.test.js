import { describe, it, expect } from 'vitest';

import { validateCookiesContent } from '../src/yt-dlp.js';

// /health/ready used to report "configured" for any non-empty
// YTDLP_COOKIES — a bad paste still looked fine while the platforms kept
// asking for sign-in. Validation reads the file yt-dlp actually gets and
// checks it is a real Netscape cookies file carrying an Instagram or
// Facebook login session — the session is what lets yt-dlp fetch captions
// from a datacenter IP. Only a status is ever returned — no cookie value
// is read out or logged.
const HEADER = '# Netscape HTTP Cookie File\n# This file was generated by Get cookies.txt\n\n';
const igLine = (name) =>
  `.instagram.com\tTRUE\t/\tTRUE\t1790000000\t${name}\tSESSIONVALUE1234567890`;
const fbLine = (name) =>
  `.facebook.com\tTRUE\t/\tTRUE\t1790000000\t${name}\tSESSIONVALUE1234567890`;
const igConsentLine = (name) =>
  `.instagram.com\tTRUE\t/\tFALSE\t1790000000\t${name}\tSOMEVALUE`;
const fbConsentLine = (name) =>
  `.facebook.com\tTRUE\t/\tFALSE\t1790000000\t${name}\tSOMEVALUE`;

describe('validateCookiesContent', () => {
  it('ok when an Instagram login session is present', () => {
    const content = HEADER + [igLine('sessionid'), igLine('ds_user_id')].join('\n');
    const out = validateCookiesContent(content);
    expect(out.status).toBe('ok');
    expect(out.detail).toBe('instagram session present');
  });

  it('ok when a Facebook login session is present', () => {
    const content = HEADER + [fbLine('c_user'), fbLine('xs')].join('\n');
    const out = validateCookiesContent(content);
    expect(out.status).toBe('ok');
    expect(out.detail).toBe('facebook session present');
  });

  it('ok when both platforms have a session, and names both', () => {
    const content = HEADER + [igLine('sessionid'), fbLine('c_user'), fbLine('xs')].join('\n');
    const out = validateCookiesContent(content);
    expect(out.status).toBe('ok');
    expect(out.detail).toBe('instagram + facebook sessions present');
  });

  it('missing-session when only consent cookies are present', () => {
    const content =
      HEADER +
      [igConsentLine('ig_did'), igConsentLine('mid'), fbConsentLine('datr')].join('\n');
    const out = validateCookiesContent(content);
    expect(out.status).toBe('missing-session');
  });

  it('invalid when there are no instagram.com or facebook.com lines', () => {
    const content =
      HEADER + '.youtube.com\tTRUE\t/\tTRUE\t1790000000\tSID\tVALUE';
    expect(validateCookiesContent(content).status).toBe('invalid');
  });

  it('invalid for empty or garbage content', () => {
    expect(validateCookiesContent('').status).toBe('invalid');
    expect(validateCookiesContent(null).status).toBe('invalid');
    expect(validateCookiesContent('just some pasted text').status).toBe('invalid');
  });
});
