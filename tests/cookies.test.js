import { describe, it, expect } from 'vitest';

import { validateCookiesContent } from '../src/yt-dlp.js';

// /health/ready used to report "configured" for any non-empty
// YTDLP_COOKIES — a bad paste still looked fine while YouTube kept asking
// for sign-in. Validation reads the file yt-dlp actually gets and checks
// it is a real Netscape cookies file carrying a login session. Only a
// status is ever returned — no cookie value is read out or logged.
const HEADER = '# Netscape HTTP Cookie File\n# This file was generated by Get cookies.txt\n\n';
const sessionLine = (name) =>
  `.youtube.com\tTRUE\t/\tTRUE\t1790000000\t${name}\tSESSIONVALUE1234567890`;
const consentLine = (name) =>
  `.youtube.com\tTRUE\t/\tFALSE\t1790000000\t${name}\tSOMEVALUE`;

describe('validateCookiesContent', () => {
  it('ok when a YouTube login session is present', () => {
    const content =
      HEADER +
      ['SID', 'HSID', 'SSID', 'APISID', 'SAPISID'].map(sessionLine).join('\n');
    const out = validateCookiesContent(content);
    expect(out.status).toBe('ok');
  });

  it('missing-session when only consent cookies are present', () => {
    const content =
      HEADER + ['CONSENT', 'PREF', 'VISITOR_INFO1_LIVE'].map(consentLine).join('\n');
    const out = validateCookiesContent(content);
    expect(out.status).toBe('missing-session');
  });

  it('invalid when there are no youtube.com lines', () => {
    const content =
      HEADER + '.google.com\tTRUE\t/\tTRUE\t1790000000\tSID\tVALUE';
    expect(validateCookiesContent(content).status).toBe('invalid');
  });

  it('invalid for empty or garbage content', () => {
    expect(validateCookiesContent('').status).toBe('invalid');
    expect(validateCookiesContent(null).status).toBe('invalid');
    expect(validateCookiesContent('just some pasted text').status).toBe('invalid');
  });
});
